# Guia/agência pessoa física vem no bruto com CNPJ de MEI na frente ("28.122.685 FULANO") ou
# CPF no fim ("FULANO 11384436707"); o dashboard grava só o nome. Tirado antes de comparar.
_DOC_RE = __import__('re').compile(r'^\s*\d{2}\.\d{3}\.\d{3}\s+|\s+\d{10,11}\s*$')

# ── FUNCOES DE REGRA ──────────────────────────────────────────────────────────

def deve_excluir(nome):
    n = nome.strip().upper()
    if n in {e.upper() for e in EXCLUIR_EXATOS}:
        return True
    for p in EXCLUIR_PREFIXO:
        if n.startswith(p.upper()):
            return True
    return False

def normalizar(nome):
    n = _DOC_RE.sub('', nome.strip()).strip().rstrip('¶').strip()
    if n in CANONICAL:
        return CANONICAL[n]
    nu = n.upper()
    for k, v in CANONICAL.items():
        if k.upper() == nu:
            return v
    if nu.startswith('INTERTOURING'):
        return 'INTERTOURING AG. DE VIAG. E TUR. LTDA.'
    return nu

